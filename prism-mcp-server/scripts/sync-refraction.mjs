#!/usr/bin/env node
// Regenerate utils/refraction-tokens.js from the design system's generated theme CSS.
//
//   node scripts/sync-refraction.mjs           rewrite utils/refraction-tokens.js
//   node scripts/sync-refraction.mjs --check   exit 1 if it is stale (CI / tests)
//
// Source: ../design/themes.js (Lead Designer, generated from design/tokens.json), the
// same PRISM_DARK_CSS / PRISM_LIGHT_CSS strings the App Shell pastes into
// THEME_REGISTRY. utils/themes.js splits each map into the theme contract (+ the
// shell's --cs-topnav-* chrome tokens) and the --rf-* Refraction layer.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
export const DESIGN_THEMES = path.resolve(HERE, '..', '..', 'design', 'themes.js');
export const OUT = path.resolve(HERE, '..', 'utils', 'refraction-tokens.js');

/** Parse one `:root{…}` block into { '--token': value } (values never contain ';'). */
export function parseRootTokens(css) {
  const m = /:root\s*\{([\s\S]*)\}/.exec(String(css || ''));
  const out = {};
  if (!m) return out;
  for (const decl of m[1].split(';')) {
    const i = decl.indexOf(':');
    if (i < 0) continue;
    const k = decl.slice(0, i).trim();
    const v = decl.slice(i + 1).trim();
    if (k.startsWith('--') && v) out[k] = v;
  }
  return out;
}

export async function buildSource(designPath = DESIGN_THEMES) {
  const d = await import(pathToFileURL(designPath).href);
  const night = parseRootTokens(d.PRISM_DARK_CSS);
  const day = parseRootTokens(d.PRISM_LIGHT_CSS);
  const obj = (o) => `{\n${Object.entries(o).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n')}\n}`;
  return [
    '// GENERATED by scripts/sync-refraction.mjs from design/themes.js — do not hand-edit.',
    `// Refraction ${d.PRISM_VERSION}: the complete :root maps of Prism Night (prism-dark) and Prism Day`,
    '// (prism-light) — the theme contract, the shell\'s --cs-topnav-* chrome tokens and the --rf-* layer.',
    `export const REFRACTION_VERSION = ${JSON.stringify(d.PRISM_VERSION)};`,
    `export const PRISM_NIGHT = ${obj(night)};`,
    `export const PRISM_DAY = ${obj(day)};`,
    '',
  ].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (!fs.existsSync(DESIGN_THEMES)) { console.error(`sync-refraction: ${DESIGN_THEMES} not found`); process.exit(1); }
  const next = await buildSource();
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (cur !== next) { console.error('sync-refraction: utils/refraction-tokens.js is stale — run node scripts/sync-refraction.mjs'); process.exit(1); }
    console.log('sync-refraction: up to date');
  } else if (cur === next) console.log('sync-refraction: already up to date');
  else { fs.writeFileSync(OUT, next); console.log(`sync-refraction: wrote ${path.relative(process.cwd(), OUT)}`); }
}
