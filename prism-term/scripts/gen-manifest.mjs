// Regenerate src/facets/manifest.js — the static list of facet modules.
//
//   node scripts/gen-manifest.mjs           write it
//   node scripts/gen-manifest.mjs --check   exit 1 if it is out of date (tests/CI)
//
// Every *.js file in src/facets/<gallery>/ is a facet module. Files starting
// with "_" are shared helpers for a gallery and are skipped.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { GALLERY_IDS } from '../src/facets/galleries.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.resolve(HERE, '..', 'src', 'facets');
const OUT = path.join(DIR, 'manifest.js');

const files = [];
for (const entry of fs.readdirSync(DIR, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  if (!GALLERY_IDS.includes(entry.name)) throw new Error(`src/facets/${entry.name}/ is not a gallery (${GALLERY_IDS.join(', ')})`);
  for (const f of fs.readdirSync(path.join(DIR, entry.name)).sort()) {
    if (f.endsWith('.js') && !f.startsWith('_')) files.push(`${entry.name}/${f}`);
  }
}
files.sort((a, b) => GALLERY_IDS.indexOf(a.split('/')[0]) - GALLERY_IDS.indexOf(b.split('/')[0]) || a.localeCompare(b));

// Several people add facets at once: a module that doesn't import cleanly yet is
// left out (with a warning) instead of breaking the registry for everyone.
// `--strict` (used by the release check) fails instead.
const { pathToFileURL } = await import('node:url');
const skipped = [];
for (const f of [...files]) {
  try {
    const mod = await import(pathToFileURL(path.join(DIR, f)).href);
    const exp = mod.default ?? mod.facets;
    if (!exp || (Array.isArray(exp) ? !exp.every((x) => typeof x?.setup === 'function') : typeof exp.setup !== 'function')) throw new Error('default export must be a facet or an array of facets');
  } catch (err) {
    skipped.push(`${f}: ${String(err?.message || err).split('\n')[0]}`);
    files.splice(files.indexOf(f), 1);
  }
}
if (skipped.length) {
  console.warn(`skipped ${skipped.length} module(s) that don't load yet:\n  ${skipped.join('\n  ')}`);
  if (process.argv.includes('--strict')) process.exit(1);
}

const body = `// GENERATED by scripts/gen-manifest.mjs — do not edit. Run \`npm run facets:manifest\`.
${files.map((f, i) => `import * as m${i} from './${f}';`).join('\n')}

export const FACET_MODULES = [
${files.map((f, i) => `  ['${f}', m${i}],`).join('\n')}
];
`;

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (cur !== body) { console.error('src/facets/manifest.js is out of date — run `npm run facets:manifest`'); process.exit(1); }
  console.log(`manifest up to date (${files.length} modules)`);
} else {
  fs.writeFileSync(OUT, body);
  console.log(`wrote src/facets/manifest.js (${files.length} modules)`);
}
