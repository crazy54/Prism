// Bitmap fonts for big text.
//
// Glyphs are authored as rows of '#' (ink) and '.' (paper) so they stay
// readable — and editable — in source. Widths are proportional (punctuation is
// narrow; digits are always full width so numbers stay tabular). A glyph has
// exactly `height` rows, or `height + descent` rows for letters that drop below
// the baseline (g, j, p, q, y in `standard`).
//
//   standard  5×7 + 1 descender row, upper and lower case — classic LCD feel
//   tiny      3×5 caps & digits — compact KPI numbers and labels
//   bold      6×7 caps & digits with 2-pixel stems — display weight
//
// Characters a font lacks fall back to uppercase, then to a hollow "tofu" box.

