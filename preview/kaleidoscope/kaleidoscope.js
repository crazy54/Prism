// ── start ────────────────────────────────────────────────────────────────────────
const ready = (async () => {
  try {
    // Cache-busting: the site build writes <meta name="prism-build"> (Cloudflare caches assets for hours). Frame files are
    // content-hashed by name, so only decks.json needs the build id.
    const decksUrl = new URL('assets/decks.json', location.href);
    const build = document.querySelector('meta[name="prism-build"]')?.content;
    if (build) decksUrl.searchParams.set('v', build);
    const r = await fetch(decksUrl);
    if (!r.ok) throw new Error(`decks.json: HTTP ${r.status}`);
    manifest = await r.json();
  } catch (err) {
    console.error('[kaleidoscope] the deck frames could not load; the decks stay on VS Code:', err);
    return;
  }
  current = manifest.initial;
  for (const v of views) for (const s of v.slots) if (s.hash) images.set(s.hash, Promise.resolve(s.img.complete ? s.img : new Promise((res) => s.img.addEventListener('load', () => res(s.img), { once: true }))));
  const start = APPS[q.get('app')] ? q.get('app') : null;
  if (start && start !== current) await go(start, { instant: true, calm: true });
  warm(stage.dataset.app);
  // the first turn waits for First Light (the page's entrance) to finish, so nobody misses it
  const entrance = window.PrismSite?.firstLight?.finished;
  if (entrance) await Promise.race([entrance.catch(() => {}), new Promise((r) => setTimeout(r, 4000))]);
  schedule(entrance ? 700 : FIRST_MS);
})();

// QA hooks (screenshots and GIF frames): freeze the turn from one app into another at t (0–1 of the whole wave)
const still = () => {
  for (const el of [...wins, byId('kd-front'), byId('kd-caption')]) { el.style.transition = 'none'; el.classList.remove('is-new'); }
};
async function settle(id) {
  await ready;
  setPaused(true);
  pending = id;          // any turn still queued gives way …
  await busy;            // … and the one in flight finishes first
  await busy;
  const app = manifest.apps[id];
  await Promise.all(refsOf(app).map((r) => load(refHash(r))));
  showScreen(id); still();
  canvasesOn(false);
  stage.classList.remove('is-turning');
  for (const v of views) for (const s of v.slots) if (!s.pin) setSlot(s, targetFor(app, v, s));
  current = id;
  await Promise.all([...document.querySelectorAll('.kd-f')].map((i) => i.decode().catch(() => {})));
}
