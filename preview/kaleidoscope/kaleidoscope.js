  settle,
  async freeze(id, t, from) {
    await ready;
    setPaused(true);
    if (from) await settle(from);
    const app = manifest.apps[id];
    await Promise.all(refsOf(app).map((r) => load(refHash(r))));
    showScreen(id); still();
    await plan(app);
    for (const v of views) for (const it of v.plan?.items || []) { it.swapped = false; it.landed = false; setSlot(it.s, it.from); }
    canvasesOn(true);
    stage.classList.add('is-turning');
    const total = DUR + STAGGER + PLUS_OFFSET;
    for (const a of stage.querySelector('.kd-stage-flare').getAnimations()) { a.pause(); a.currentTime = t * 1350; }
    frame(t * total);
    return total;
  },
