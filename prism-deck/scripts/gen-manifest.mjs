// Regenerate the static module manifests:
//   src/themes/_manifest.js   every src/themes/*.js
//   src/glyphs/_manifest.js   every src/glyphs/<category>/*.js
//   src/facets/manifest.js    every src/facets/<gallery>/*.js
// Files starting with "_" are helpers and are skipped.
//
//   node scripts/gen-manifest.mjs            write them
//   node scripts/gen-manifest.mjs --check    exit 1 if any is out of date (tests/CI)
//   node scripts/gen-manifest.mjs --strict   fail (instead of skipping) when a module doesn't load
//
// Many people add modules at once: a module that doesn't import cleanly yet is left
// out with a warning instead of breaking the registry for everyone.

import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { GALLERY_IDS } from '../src/facets/galleries.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.resolve(HERE, '..', 'src');
const KEBAB = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

const js = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.js') && !f.startsWith('_')).sort() : []);
const subdirs = (dir) => (fs.existsSync(dir) ? fs.readdirSync(dir, { withFileTypes: true }).filter((e) => e.isDirectory() && !e.name.startsWith('_')).map((e) => e.name).sort() : []);

export const MANIFESTS = {
  themes: {
    out: 'themes/_manifest.js', name: 'THEME_MODULES', base: 'themes',
    files: () => js(path.join(SRC, 'themes')),
    ok: (exp) => exp && typeof exp.resolve === 'function',
  },
  glyphs: {
    out: 'glyphs/_manifest.js', name: 'GLYPH_MODULES', base: 'glyphs',
    files() {
      const out = [];
      for (const c of subdirs(path.join(SRC, 'glyphs'))) {
        if (!KEBAB.test(c)) throw new Error(`src/glyphs/${c}/ must be a kebab-case category`);
        for (const f of js(path.join(SRC, 'glyphs', c))) out.push(`${c}/${f}`);
      }
      return out;
    },
    ok: (exp) => exp && typeof exp.draw === 'function' && Array.isArray(exp.stateNames),
  },
  facets: {
    out: 'facets/manifest.js', name: 'FACET_MODULES', base: 'facets',
    files() {
      const out = [];
      for (const g of subdirs(path.join(SRC, 'facets'))) {
        if (!GALLERY_IDS.includes(g)) throw new Error(`src/facets/${g}/ is not a gallery (${GALLERY_IDS.join(', ')})`);
        for (const f of js(path.join(SRC, 'facets', g))) out.push(`${g}/${f}`);
      }
      return out.sort((a, b) => GALLERY_IDS.indexOf(a.split('/')[0]) - GALLERY_IDS.indexOf(b.split('/')[0]) || a.localeCompare(b));
    },
    ok: (exp) => exp && (Array.isArray(exp) ? exp.every((x) => typeof x?.render === 'function') : typeof exp.render === 'function'),
  },
};

/** One manifest's text, skipping modules that fail to import or don't export the right thing. */
export async function manifestBody(m) {
  const files = m.files();
  const skipped = [];
  for (const f of [...files]) {
    try {
      const mod = await import(pathToFileURL(path.join(SRC, m.base, f)).href);
      if (!m.ok(mod.default ?? mod.facets)) throw new Error(`default export is not a valid ${m.base.replace(/s$/, '')}`);
    } catch (err) {
      skipped.push(`${m.base}/${f}: ${String(err?.message || err).split('\n')[0]}`);
      files.splice(files.indexOf(f), 1);
    }
  }
  const imports = files.map((f, i) => `import * as m${i} from './${f}';`).join('\n');
  const rows = files.map((f, i) => `  ['${f}', m${i}],`).join('\n');
  const body = `// GENERATED by scripts/gen-manifest.mjs — do not edit. Run \`npm run facets:manifest\`.\n${imports}\n\nexport const ${m.name} = [\n${rows}\n];\n`;
  return { ...m, body, count: files.length, skipped };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  // Themes and glyphs first. Facets import their registries, and ES modules are cached
  // per process, so facets are processed in a fresh child process that sees the new manifests.
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const facetsPhase = args.includes('--phase=facets');
  let stale = false, skippedAny = false;
  for (const m of facetsPhase ? [MANIFESTS.facets] : [MANIFESTS.themes, MANIFESTS.glyphs]) {
    const r = await manifestBody(m);
    const file = path.join(SRC, r.out);
    const cur = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
    if (r.skipped.length) { skippedAny = true; console.warn(`skipped ${r.skipped.length} module(s) that don't load yet:\n  ${r.skipped.join('\n  ')}`); }
    if (check) {
      if (cur !== r.body) { console.error(`src/${r.out} is out of date — run \`npm run facets:manifest\``); stale = true; }
      else console.log(`src/${r.out} up to date (${r.count} modules)`);
      continue;
    }
    if (cur !== r.body) fs.writeFileSync(file, r.body);
    console.log(`${cur === r.body ? 'up to date' : 'wrote'}: src/${r.out} (${r.count} modules)`);
  }
  if (!facetsPhase) {
    const res = spawnSync(process.execPath, [fileURLToPath(import.meta.url), '--phase=facets', ...args], { stdio: 'inherit' });
    if (res.status) process.exit(res.status);
  }
  if ((skippedAny && args.includes('--strict')) || stale) process.exit(1);
}
