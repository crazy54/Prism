// Regenerate src/scene/tokens.js from the design language (Prism-ds/design/tokens.json).
//
//   node scripts/sync-tokens.mjs            write it (requires design/TOKENS-READY)
//   node scripts/sync-tokens.mjs --check    exit 1 if src/scene/tokens.js is out of date
//
// Maps color.night / color.day, the deck key grammar (deck.*), the Refraction
// material (rf.*, deck.material) and the 12-stop Spectrum (ink / vivid / wash tiers
// per mode) into the shape the prism theme and the engine read.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const DESIGN = path.resolve(ROOT, '..', 'design');
const OUT = path.join(ROOT, 'src', 'scene', 'tokens.js');

const hexes = (s) => [...String(s).matchAll(/#[0-9a-f]{6}\b/gi)].map((m) => m[0].toLowerCase());
const alphaOf = (s, fallback) => { const m = String(s).match(/rgba\([^)]*,\s*([\d.]+)\)/); return m ? +m[1] : fallback; };
const at72 = (v144) => v144 / 2;

export function deckTokens(t) {
  const mode = (name, C, rf, mat) => {
    const glass = hexes(mat.fill);
    return {
      bg: C.bg.hex, bgDeep: C['bg-deep'].hex, panel: C.panel.hex, panel2: C.panel2.hex, card: C.card.hex,
      line: C.line.hex, lineStrong: C['line-strong'].hex, lineControl: C['line-control'].hex,
      ink: mat.ink || C.ink.hex, muted: mat.muted || C.muted.hex, dim: C.dim.hex, faint: C.faint.hex,
      accent: C.accent.hex, accentHi: C['accent-hi'].hex, accent2: C.accent2.hex, accentInk: C['accent-ink'].hex,
      info: C.info.hex, pos: C.pos.hex, warn: C.warn.hex, neg: C.neg.hex, crit: C.crit.hex,
      glassTop: glass[0], glassMid: glass[1] || glass[0], glassBottom: glass[2] || glass[1] || glass[0],
      edge: name === 'night' ? '#ffffff' : '#ffffff', edgeOpacity: name === 'night' ? alphaOf(mat.edge, 0.08) : 1,
      beam: (rf['beam-core'] || '#ffffff').toLowerCase(), beamOpacity: 0.92, sheenOpacity: name === 'night' ? 0.1 : 0.12,
      spectrum: name === 'night' ? { l: 0.715, c: 0.13 } : { l: 0.646, c: 0.16 },
      stops: t.spectrum.stops.map((s) => ({ name: s.name, h: s.h, lambda: String(s.lambda || '').replace('λ', '').trim(), ink: s[name].ink.hex, vivid: s[name].vivid.hex, wash: typeof s[name].wash === 'object' ? s[name].wash.hex : null })),
    };
  };
  const D = t.deck;
  const deckHue = (t.galleries.surfaces || []).find((s) => s.id === 'deck');
  return {
    source: `design/tokens.json v${t.version}`,
    version: t.version,
    modes: { night: mode('night', t.color.night, t.rf.night, D.material.night), day: mode('day', t.color.day, t.rf.day, D.material.day) },
    deck: {
      surfaceHue: deckHue?.h ?? 66, surfaceLambda: deckHue?.lambda ?? 'λ 584',
      // @72 values (the engine scales by key size / 72)
      safe: { bleed: at72(D.safe.bleed), content: at72(D.safe.content), text: at72(D.safe.text) },
      grid: at72(D.grid.unit),
      type: {
        value: { size: D.type.value.sizeAt72, weight: D.type.value.weight, tracking: parseFloat(D.type.value.tracking) || 0 },
        label: { size: D.type.label.sizeAt72, weight: D.type.label.weight, tracking: parseFloat(D.type.label.tracking) || 0, maxLines: D.type.label.maxLines },
        micro: { size: D.type.micro.sizeAt72, weight: D.type.micro.weight, tracking: parseFloat(D.type.micro.tracking) || 0, caps: D.type.micro.transform === 'uppercase' },
        dialValue: { size: D.type.dialValue.size, weight: D.type.dialValue.weight },
        dialLabel: { size: D.type.dialLabel.size, weight: D.type.dialLabel.weight, tracking: parseFloat(D.type.dialLabel.tracking) || 0, caps: D.type.dialLabel.transform === 'uppercase' },
        minimum: 8,
      },
      index: { w: 16, h: 2, bottom: 6, offOpacity: 0.45, glow: 3 },
      ring: { on: 1.5, alert: 2 },
      notch: 12,
      wash: 0.22,
      alertBreath: { hz: 1, min: 0.55, max: 1, holdAfter: 10 },
      busyLap: 1.2,
      fps: { cap: 10, key: 10, span: 10, strip: 12, screen: 8, deck: 8 },
      motion: { arrive: (t.motion?.duration?.slow ?? 400) / 1000, press: (t.motion?.duration?.base ?? 240) / 1000, fast: (t.motion?.duration?.fast ?? 140) / 1000 },
    },
  };
}

function moduleText(tok) {
  return `// GENERATED by scripts/sync-tokens.mjs from Prism-ds/design/tokens.json — do not edit.
// The Refraction design language for decks: per-mode palette + material, the 12-stop
// Spectrum (ink / vivid / wash tiers), and the Stream Deck key grammar (@72 px units).
export const TOKENS = ${JSON.stringify(tok, null, 2)};
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (!fs.existsSync(path.join(DESIGN, 'TOKENS-READY'))) { console.error('design/TOKENS-READY not found — tokens are not published yet'); process.exit(1); }
  const tokens = JSON.parse(fs.readFileSync(path.join(DESIGN, 'tokens.json'), 'utf8'));
  const text = moduleText(deckTokens(tokens));
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== text) { console.error('src/scene/tokens.js is out of date — run `npm run sync-tokens`'); process.exit(1); }
    console.log('tokens up to date');
  } else { fs.writeFileSync(OUT, text); console.log(`wrote src/scene/tokens.js from design/tokens.json v${tokens.version}`); }
}
