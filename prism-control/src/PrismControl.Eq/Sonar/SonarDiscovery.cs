using System.Net;
using System.Net.Http;
using System.Net.Security;
using System.Net.Sockets;
using System.Security.Cryptography.X509Certificates;
using System.Text.Json.Nodes;
using PrismControl.Core.Hosting;

namespace PrismControl.Eq.Sonar;

/// <summary>The outcome of one discovery: Sonar's base URL, or why there is none.</summary>
public sealed record SonarDiscoveryResult(EqAvailability Availability, Uri? BaseUri)
{
    public static SonarDiscoveryResult Fail(EqAvailabilityCode code, string reason, string? detail = null) => new(new EqAvailability(code, reason, detail), null);
}

/// <summary>
/// Finds Sonar's random local port (research eq.md §3):
/// <c>%PROGRAMDATA%\SteelSeries\GG\coreProps.json</c> (then the Engine 3 copy) → <c>ggEncryptedAddress</c> →
/// <c>GET https://&lt;gg&gt;/subApps</c> over the GG core's self-signed TLS → <c>subApps.sonar.metadata.webServerAddress</c>.
/// Read-only: discovery never writes anything.
/// </summary>
public sealed class SonarDiscovery : IDisposable
{
    /// <summary>The GG core's certificate subject (self-signed, regenerated by GG installs).</summary>
    public const string GgCertificateSubject = "CN=SteelSeries A/S";

    private readonly IReadOnlyList<string> _corePropsPaths;
    private readonly ILog _log;
    private readonly HttpClient _gg;

    public SonarDiscovery(IReadOnlyList<string> corePropsPaths, ILog log, TimeSpan? timeout = null)
    {
        _corePropsPaths = corePropsPaths;
        _log = log;
        _gg = new HttpClient(CreateGgHandler(), disposeHandler: true) { Timeout = timeout ?? TimeSpan.FromSeconds(5) };
    }

    /// <summary>The GG path first, then the older SteelSeries Engine 3 path that community libraries use.</summary>
    public static IReadOnlyList<string> DefaultCorePropsPaths()
    {
        var pd = Environment.GetFolderPath(Environment.SpecialFolder.CommonApplicationData);
        return [Path.Combine(pd, "SteelSeries", "GG", "coreProps.json"), Path.Combine(pd, "SteelSeries", "SteelSeries Engine 3", "coreProps.json")];
    }

    public IReadOnlyList<string> CorePropsPaths => _corePropsPaths;

    /// <summary>
    /// A dedicated handler for the GG core only. It accepts the self-signed certificate only when the host is loopback
    /// and the leaf subject is exactly <see cref="GgCertificateSubject"/>; validation is never turned off globally.
    /// </summary>
    public static SocketsHttpHandler CreateGgHandler() => new()
    {
        UseProxy = false,
        AllowAutoRedirect = false,
        ConnectTimeout = TimeSpan.FromSeconds(3),
        PooledConnectionLifetime = TimeSpan.FromMinutes(2),
        SslOptions = new SslClientAuthenticationOptions { RemoteCertificateValidationCallback = ValidateGgCertificate },
    };

    /// <summary>Public for tests: the TLS rule for the GG core.</summary>
    public static bool ValidateGgCertificate(object sender, X509Certificate? certificate, X509Chain? chain, SslPolicyErrors errors)
    {
        if (errors == SslPolicyErrors.None) return true;
        if (certificate is null || (errors & SslPolicyErrors.RemoteCertificateNotAvailable) != 0) return false;
        var host = sender switch
        {
            SslStream s => s.TargetHostName,
            HttpRequestMessage m => m.RequestUri?.Host,
            _ => null,
        };
        if (!IsLoopbackHost(host)) return false;
        return string.Equals(certificate.Subject, GgCertificateSubject, StringComparison.Ordinal);
    }

    public static bool IsLoopbackHost(string? host)
    {
        if (string.IsNullOrEmpty(host)) return false;
        if (host.Equals("localhost", StringComparison.OrdinalIgnoreCase)) return true;
        return IPAddress.TryParse(host.Trim('[', ']'), out var ip) && IPAddress.IsLoopback(ip);
    }

    /// <summary>Accepts "http://127.0.0.1:51446" or a bare "127.0.0.1:51446" (older builds). Loopback only.</summary>
    public static Uri? ParseSonarAddress(string? address)
    {
        if (string.IsNullOrWhiteSpace(address)) return null;
        var a = address.Trim();
        if (!a.Contains("://", StringComparison.Ordinal)) a = "http://" + a;
        if (!Uri.TryCreate(a, UriKind.Absolute, out var uri)) return null;
        if (uri.Scheme != Uri.UriSchemeHttp && uri.Scheme != Uri.UriSchemeHttps) return null;
        if (!IsLoopbackHost(uri.Host)) return null;
        return new Uri(uri.GetLeftPart(UriPartial.Authority).TrimEnd('/') + "/");
    }

    /// <summary>The first readable discovery file's <c>ggEncryptedAddress</c> (null when GG is not installed or never started).</summary>
    public (string? Address, string? File) ReadCoreProps()
    {
        foreach (var path in _corePropsPaths)
        {
            try
            {
                if (!File.Exists(path)) continue;
                using var fs = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite | FileShare.Delete);
                var node = JsonNode.Parse(fs);
                var addr = node?["ggEncryptedAddress"]?.GetValue<string>();
                if (!string.IsNullOrWhiteSpace(addr)) return (addr.Trim(), path);
            }
            catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or System.Text.Json.JsonException or InvalidOperationException)
            {
                _log.Debug($"Sonar discovery: could not read {path}: {ex.Message}");
            }
        }
        return (null, null);
    }

    public async Task<SonarDiscoveryResult> DiscoverAsync(CancellationToken ct)
    {
        var (gg, file) = ReadCoreProps();
        if (gg is null)
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.NotRunning, "SteelSeries GG isn't running.", "No GG discovery file (coreProps.json).");
        var hostPort = gg.Contains("://", StringComparison.Ordinal) ? new Uri(gg).Authority : gg;
        var ggUri = new Uri("https://" + hostPort + "/");
        if (!IsLoopbackHost(ggUri.Host))
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.Error, "SteelSeries GG reported a non-local address; refusing to use it.", gg);

        JsonNode? subApps;
        try
        {
            using var resp = await _gg.GetAsync(new Uri(ggUri, "subApps"), ct).ConfigureAwait(false);
            if (!resp.IsSuccessStatusCode)
                return SonarDiscoveryResult.Fail(EqAvailabilityCode.Starting, "SteelSeries GG is starting…", $"GET /subApps → {(int)resp.StatusCode}");
            subApps = JsonNode.Parse(await resp.Content.ReadAsStringAsync(ct).ConfigureAwait(false));
        }
        catch (HttpRequestException ex) when (ex.InnerException is System.Security.Authentication.AuthenticationException)
        {
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.Error, "Couldn't verify SteelSeries GG's local certificate.", ex.InnerException.Message);
        }
        catch (HttpRequestException ex) when (ex.InnerException is SocketException || ex.HttpRequestError == HttpRequestError.ConnectionError)
        {
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.NotRunning, "SteelSeries GG isn't running.", $"{hostPort} refused the connection ({Path.GetFileName(file)}).");
        }
        catch (HttpRequestException ex)
        {
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.NotRunning, "SteelSeries GG isn't responding.", ex.Message);
        }
        catch (TaskCanceledException) when (!ct.IsCancellationRequested)
        {
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.NotRunning, "SteelSeries GG isn't responding.", "GET /subApps timed out.");
        }
        catch (System.Text.Json.JsonException ex)
        {
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.Error, "SteelSeries GG sent an unexpected answer.", ex.Message);
        }

        var sonar = subApps?["subApps"]?["sonar"];
        if (sonar is null) return SonarDiscoveryResult.Fail(EqAvailabilityCode.NotRunning, "Sonar isn't installed in SteelSeries GG.");
        if (Bool(sonar["isEnabled"]) == false) return SonarDiscoveryResult.Fail(EqAvailabilityCode.Disabled, "Sonar is turned off in GG.");
        var address = ParseSonarAddress(Str(sonar["metadata"]?["webServerAddress"]));
        if (Bool(sonar["isRunning"]) == false || Bool(sonar["isReady"]) == false || address is null)
            return SonarDiscoveryResult.Fail(EqAvailabilityCode.Starting, "Sonar is starting…");
        _log.Debug($"Sonar discovered at {address}");
        return new SonarDiscoveryResult(EqAvailability.Ok, address);
    }

    private static bool? Bool(JsonNode? n) => n is JsonValue v && v.TryGetValue<bool>(out var b) ? b : null;
    private static string? Str(JsonNode? n) => n is JsonValue v && v.TryGetValue<string>(out var s) ? s : null;

    public void Dispose() => _gg.Dispose();
}
