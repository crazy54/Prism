<#
.SYNOPSIS
  Builds, tests, publishes and packs Prism Control. Never installs anything.

.DESCRIPTION
  1. Checks the generated Refraction tokens are in sync with Prism-ds/design/tokens.json (skipped if absent).
  2. Builds PrismControl.sln.
  3. Publishes src/PrismRelay (prism-relay.exe, NativeAOT unless -RelayNoAot) to artifacts/relay. With -Version, also
     regenerates Smart's bundled profiles (src/PrismControl.Smart/plugin/profiles) for that version.
  4. Runs the unit + integration tests (core and every domain test project). Integration tests are read-only probes
     against this PC (Core Audio, iCUE, LHM, Sonar); -SkipIntegration leaves them out. The relay tests run the
     published prism-relay.exe (PRISM_RELAY_EXE). Sight runs without its integration category (its owner's rule).
  5. Publishes src/PrismControl as a self-contained single-file win-x64 exe (artifacts/publish/PrismControl.exe).
  6. Packs dist/com.jeremyfhall.prismcontrol.sdPlugin + dist/com.jeremyfhall.prismcontrol.streamDeckPlugin
     (manifest generated by the exe from its [StreamDeckAction] attributes plus the modules' bundled Profiles, validated
     against the Elgato schemas; bin/prism-relay.exe; extension/ without tests, tools or keys).
  7. Runs the end-to-end tests: the published exe against the fake Stream Deck app.

.EXAMPLE
  pwsh tools/build.ps1
  pwsh tools/build.ps1 -Version 0.2.0.0 -Trim
  pwsh tools/build.ps1 -SkipTests        # publish + pack only
  pwsh tools/build.ps1 -SkipIntegration  # unit + E2E only (no read-only probes of the real audio/iCUE/LHM/Sonar)
  pwsh tools/build.ps1 -RelayNoAot       # no VC tools: prism-relay.exe as a trimmed single file instead of NativeAOT
#>
[CmdletBinding()]
param(
    [string]$Version,
    [string]$Configuration = 'Release',
    [switch]$Trim,
    [switch]$SkipTests,
    [switch]$SkipE2E,
    [switch]$SkipIntegration,
    [switch]$RelayNoAot
)

$ErrorActionPreference = 'Stop'
# House rules: no ASP.NET dev certificate, no telemetry.
$env:DOTNET_GENERATE_ASPNET_CERTIFICATE = 'false'
$env:DOTNET_CLI_TELEMETRY_OPTOUT = '1'
$env:DOTNET_NOLOGO = '1'

$root = Split-Path -Parent $PSScriptRoot
$dotnet = 'C:\Program Files\dotnet\dotnet.exe'
if (-not (Test-Path $dotnet)) { $dotnet = 'dotnet' }

function Step([string]$name) { Write-Host "`n=== $name" -ForegroundColor Cyan }
function Invoke([string[]]$cmd) {
    & $dotnet @cmd
    if ($LASTEXITCODE -ne 0) { throw "dotnet $($cmd -join ' ') failed with exit code $LASTEXITCODE" }
}

Push-Location $root
try {
    $versionArgs = @()
    if ($Version) {
        if ($Version -notmatch '^\d+\.\d+\.\d+\.\d+$') { throw "-Version must have four parts, e.g. 0.2.0.0" }
        $versionArgs = @("-p:Version=$Version")
    }

    $tokens = if ($env:PRISM_TOKENS_JSON) { $env:PRISM_TOKENS_JSON } else { Join-Path $root '..\..\Prism-ds\design\tokens.json' }
    if (Test-Path $tokens) {
        Step 'Tokens in sync'
        Invoke @('run', '--project', 'tools/PrismControl.TokensGen', '-c', $Configuration, '--', '--check', '--tokens', $tokens)
    } else {
        Write-Warning "tokens.json not found at $tokens; skipping the sync check."
    }

    Step "Build ($Configuration)"
    Invoke (@('build', 'PrismControl.sln', '-c', $Configuration) + $versionArgs)

    # prism-relay.exe: Chrome/Edge native-messaging host + agent hook relay (never referenced by the plugin exe).
    # NativeAOT's link step runs vcvarsall.bat, which calls vswhere.exe by bare name: the VS Installer folder must be on
    # PATH, and no MSBuild node started without that PATH may be reused (--disable-build-servers). See platform/DEVIATIONS.md item 25.
    Step "Publish prism-relay ($(if ($RelayNoAot) { 'trimmed single file' } else { 'NativeAOT' }))"
    $relayOut = Join-Path $root 'artifacts\relay'
    if (Test-Path $relayOut) { Remove-Item $relayOut -Recurse -Force }
    $vsInstaller = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer'
    $savedPath = $env:PATH
    try {
        if ((Test-Path $vsInstaller) -and -not (($env:PATH -split ';') -contains $vsInstaller)) { $env:PATH = "$vsInstaller;$env:PATH" }
        $relayArgs = @('publish', 'src/PrismRelay', '-c', $Configuration, '-r', 'win-x64', '--disable-build-servers', '-o', $relayOut) + $versionArgs
        if ($RelayNoAot) { $relayArgs += '-p:PrismRelayAot=false' }
        Invoke $relayArgs
    }
    finally { $env:PATH = $savedPath }
    $relayExe = Join-Path $relayOut 'prism-relay.exe'
    Write-Host ("relay: {0:N0} bytes" -f (Get-Item $relayExe).Length)

    if ($Version) {
        # Smart's bundled "Prism Smart - <device>" profiles carry the plugin version (its staleness test compares them).
        Step "Regenerate Smart's bundled profiles for $Version"
        Invoke @('run', '--project', 'tests/PrismControl.Smart.Tests', '-c', $Configuration, '--no-build', '--',
            '--write-profiles', 'src/PrismControl.Smart/plugin/profiles', '--version', $Version)
    }

    if (-not $SkipTests) {
        Step ($(if ($SkipIntegration) { 'Unit tests (integration skipped)' } else { 'Unit + integration tests' }))
        $coreExclude = if ($SkipIntegration) { 'e2e,integration' } else { 'e2e' }
        Invoke @('run', '--project', 'tests/PrismControl.Tests', '-c', $Configuration, '--no-build', '--', '--exclude', $coreExclude)
        foreach ($domain in 'Audio', 'SystemInfo', 'Spotify', 'Eq', 'Macros', 'Cooling', 'Desktop', 'Browser', 'WinShell', 'Ai', 'Smart') {
            $domainArgs = @('run', '--project', "tests/PrismControl.$domain.Tests", '-c', $Configuration, '--no-build')
            if ($SkipIntegration) { $domainArgs += @('--', '--exclude', 'integration') }
            Invoke $domainArgs
        }
        # Sight: the integration category captures this process's own windows; its owner runs it outside CI-like runs.
        Invoke @('run', '--project', 'tests/PrismControl.Sight.Tests', '-c', $Configuration, '--no-build', '--', '--exclude', 'integration')
        # The relay's process tests run the published prism-relay.exe (else they fall back to the apphost next to the tests).
        $env:PRISM_RELAY_EXE = $relayExe
        try {
            $relayTestArgs = @('run', '--project', 'tests/PrismRelay.Tests', '-c', $Configuration, '--no-build')
            if ($SkipIntegration) { $relayTestArgs += @('--', '--exclude', 'integration') }
            Invoke $relayTestArgs
        }
        finally { Remove-Item Env:\PRISM_RELAY_EXE -ErrorAction SilentlyContinue }
    }

    Step "Publish (self-contained single-file win-x64$(if ($Trim) { ', trimmed' }))"
    $publish = Join-Path $root 'artifacts\publish'
    if (Test-Path $publish) { Remove-Item $publish -Recurse -Force }
    Invoke (@('publish', 'src/PrismControl', '-c', $Configuration, '-r', 'win-x64', '--self-contained', 'true',
        "-p:PrismTrim=$($Trim.IsPresent.ToString().ToLowerInvariant())", '-o', $publish) + $versionArgs)
    $exe = Join-Path $publish 'PrismControl.exe'
    Write-Host ("exe: {0:N1} MB" -f ((Get-Item $exe).Length / 1MB))

    Step 'Pack + validate'
    $packArgs = @('run', '--project', 'tools/PrismControl.Tools', '-c', $Configuration, '--no-build', '--', 'pack', '--exe', $exe, '--out', (Join-Path $root 'dist'), '--relay', $relayExe)
    if ($Version) { $packArgs += @('--version', $Version) }
    Invoke $packArgs

    if (-not $SkipTests -and -not $SkipE2E) {
        Step 'End-to-end (published exe vs the fake Stream Deck app)'
        $env:PRISM_CONTROL_REQUIRE_E2E = '1'
        try { Invoke @('run', '--project', 'tests/PrismControl.Tests', '-c', $Configuration, '--no-build', '--', '--category', 'e2e') }
        finally { Remove-Item Env:\PRISM_CONTROL_REQUIRE_E2E -ErrorAction SilentlyContinue }
    }

    Step 'Done'
    Write-Host "plugin folder: $(Join-Path $root 'dist\com.jeremyfhall.prismcontrol.sdPlugin')"
    Write-Host "bundle:        $(Join-Path $root 'dist\com.jeremyfhall.prismcontrol.streamDeckPlugin') (not installed)"
}
finally {
    Pop-Location
}
