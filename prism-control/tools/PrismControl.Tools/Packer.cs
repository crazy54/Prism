using System.Diagnostics;
using System.IO.Compression;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace PrismControl.Tools;

/// <summary>
/// Assembles dist/com.jeremyfhall.prismcontrol.sdPlugin and zips it into dist/com.jeremyfhall.prismcontrol.streamDeckPlugin.
/// Inputs: the published single-file exe, assets/imgs, layouts/ (+ src/*/layouts), pi/ (+ src/*/pi), src/*/plugin/profiles
/// (bundled .streamDeckProfile files + profiles.manifest.json, merged into the manifest's Profiles), the published
/// prism-relay.exe (bin/prism-relay.exe) and the browser extension (extension/, without dev folders or keys).
/// manifest.json comes from the exe itself (--emit-manifest), so it always matches the shipped action attributes.
/// Never installs anything.
/// </summary>
public static class Packer
{
    public const string PluginUuid = "com.jeremyfhall.prismcontrol";
    public const string RelayExeName = "prism-relay.exe";
    public const string ProfilesManifestName = "profiles.manifest.json";

    public sealed record Result(string PluginDir, string BundlePath, long BundleBytes, long ExeBytes, List<string> Problems);

    public static Result Pack(string repoRoot, string exePath, string outDir, string? version, TextWriter log, string? relayPath = null)
    {
        var pluginDir = Path.Combine(outDir, PluginUuid + ".sdPlugin");
        if (Directory.Exists(pluginDir)) Directory.Delete(pluginDir, recursive: true);
        Directory.CreateDirectory(Path.Combine(pluginDir, "bin"));

        File.Copy(exePath, Path.Combine(pluginDir, "bin", "PrismControl.exe"));
        CopyTree(Path.Combine(repoRoot, "assets", "imgs"), Path.Combine(pluginDir, "imgs"), null, null, WebFiles);
        // Apache 2.0: the license and (Section 4(d)) the NOTICE crediting JFH Inc. and Jeremy Francis Hall ship with every copy.
        foreach (var name in new[] { "LICENSE", "NOTICE" })
        {
            var source = new[] { Path.Combine(repoRoot, name), Path.Combine(repoRoot, "..", name) }.FirstOrDefault(File.Exists)
                ?? throw new FileNotFoundException($"{name} not found next to prism-control or at the repo root; the plugin must ship it (Apache 2.0).");
            File.Copy(source, Path.Combine(pluginDir, name + ".txt"));
        }

        var seen = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
        var problems = new List<string>();
        // prism-relay.exe (native messaging + agent hooks): RelayInstaller copies it from <plugin>/bin/ on Connect / Install hooks.
        if (relayPath is not null)
        {
            if (File.Exists(relayPath)) File.Copy(relayPath, Path.Combine(pluginDir, "bin", RelayExeName));
            else problems.Add($"relay not found: {relayPath}");
        }
        // The browser extension for "Load unpacked" (HostInstaller copies <plugin>/extension on Connect).
        CopyExtension(Path.Combine(repoRoot, "extension"), Path.Combine(pluginDir, "extension"), 0);
        CopyTree(Path.Combine(repoRoot, "layouts"), Path.Combine(pluginDir, "layouts"), seen, problems, LayoutFiles);
        CopyTree(Path.Combine(repoRoot, "pi"), Path.Combine(pluginDir, "pi"), seen, problems, WebFiles);
        // Domain projects ship their own plugin files under src/<Project>/plugin/{layouts,pi,imgs,profiles}/.
        var profileManifests = new List<string>();
        foreach (var project in Directory.EnumerateDirectories(Path.Combine(repoRoot, "src")).Order(StringComparer.Ordinal))
        {
            var plugin = Path.Combine(project, "plugin");
            CopyTree(Path.Combine(plugin, "layouts"), Path.Combine(pluginDir, "layouts"), seen, problems, LayoutFiles);
            CopyTree(Path.Combine(plugin, "pi"), Path.Combine(pluginDir, "pi"), seen, problems, WebFiles);
            CopyTree(Path.Combine(plugin, "imgs"), Path.Combine(pluginDir, "imgs"), seen, problems, WebFiles);
            CopyTree(Path.Combine(plugin, "profiles"), Path.Combine(pluginDir, "profiles"), seen, problems, ProfileFiles);
            var profileManifest = Path.Combine(plugin, "profiles", ProfilesManifestName);
            if (File.Exists(profileManifest)) profileManifests.Add(profileManifest);
        }

        // The manifest is generated by the exe from its [StreamDeckAction] attributes.
        var manifest = Path.Combine(pluginDir, "manifest.json");
        var psi = new ProcessStartInfo(Path.Combine(pluginDir, "bin", "PrismControl.exe"))
        {
            UseShellExecute = false,
            RedirectStandardOutput = true,
            RedirectStandardError = true,
            CreateNoWindow = true,
        };
        psi.ArgumentList.Add("--emit-manifest");
        psi.ArgumentList.Add(manifest);
        if (version is not null) { psi.ArgumentList.Add("--version"); psi.ArgumentList.Add(version); }
        using (var p = Process.Start(psi)!)
        {
            var stdout = p.StandardOutput.ReadToEndAsync();
            var stderr = p.StandardError.ReadToEndAsync();
            if (!p.WaitForExit(60_000)) { p.Kill(true); throw new TimeoutException("--emit-manifest timed out"); }
            log.Write(stdout.Result);
            if (stderr.Result.Length > 0) log.Write(stderr.Result);
            if (p.ExitCode != 0) problems.Add($"--emit-manifest failed (exit {p.ExitCode})");
        }

        if (File.Exists(manifest) && profileManifests.Count > 0) MergeProfiles(manifest, profileManifests, problems, log);
        if (File.Exists(manifest)) problems.AddRange(PluginValidator.ValidatePlugin(pluginDir));

        var bundle = Path.Combine(outDir, PluginUuid + ".streamDeckPlugin");
        if (File.Exists(bundle)) File.Delete(bundle);
        // A .streamDeckPlugin is a ZIP whose root holds the <uuid>.sdPlugin folder.
        ZipFile.CreateFromDirectory(pluginDir, bundle, CompressionLevel.Optimal, includeBaseDirectory: true);
        return new Result(pluginDir, bundle, new FileInfo(bundle).Length, new FileInfo(Path.Combine(pluginDir, "bin", "PrismControl.exe")).Length, problems);
    }

    /// <summary>
    /// Appends every src/*/plugin/profiles/profiles.manifest.json <c>Profiles</c> entry (Smart's bundled "Prism Smart - &lt;device&gt;"
    /// profiles) to the generated manifest. The exe's generator knows nothing about profiles, so they are merged here; the
    /// validator then checks each entry against the schema and that its <c>Name</c>.streamDeckProfile exists.
    /// </summary>
    private static void MergeProfiles(string manifestPath, List<string> profileManifests, List<string> problems, TextWriter log)
    {
        var root = JsonNode.Parse(File.ReadAllText(manifestPath))!.AsObject();
        if (root["Profiles"] is not JsonArray profiles) root["Profiles"] = profiles = new JsonArray();
        var names = new HashSet<string>(profiles.Select(e => e?["Name"]?.GetValue<string>() ?? ""), StringComparer.OrdinalIgnoreCase);
        foreach (var file in profileManifests)
        {
            JsonArray? entries;
            try { entries = JsonNode.Parse(File.ReadAllText(file))?["Profiles"] as JsonArray; }
            catch (JsonException ex) { problems.Add($"{file}: {ex.Message}"); continue; }
            if (entries is null) { problems.Add($"{file}: no Profiles array"); continue; }
            foreach (var entry in entries)
            {
                var name = entry?["Name"]?.GetValue<string>();
                if (name is null || !names.Add(name)) { problems.Add($"{file}: profile {name ?? "(no Name)"} is missing a Name or listed twice"); continue; }
                profiles.Add(entry!.DeepClone());
            }
        }
        File.WriteAllText(manifestPath, root.ToJsonString(new JsonSerializerOptions
        {
            WriteIndented = true,
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping, // same as the exe's --emit-manifest
        }) + "\n");
        log.WriteLine($"manifest: {profiles.Count} bundled profile(s) from {profileManifests.Count} profiles.manifest.json file(s)");
    }

    /// <summary>
    /// Copies the browser extension the way HostInstaller does, minus anything a user does not need: no dev folders
    /// (tests, tools, node_modules, dot-folders), no dotfiles, and nothing key-like (a private key must never ship).
    /// </summary>
    private static void CopyExtension(string from, string to, int depth)
    {
        if (!Directory.Exists(from) || depth > 8) return;
        foreach (var file in Directory.EnumerateFiles(from))
        {
            var name = Path.GetFileName(file);
            var stem = Path.GetFileNameWithoutExtension(name);
            if (name.StartsWith('.') || KeyLikeFiles.Contains(Path.GetExtension(name))
                || stem.Equals("key", StringComparison.OrdinalIgnoreCase) || stem.Contains("private", StringComparison.OrdinalIgnoreCase)) continue;
            Directory.CreateDirectory(to);
            File.Copy(file, Path.Combine(to, name), overwrite: true);
        }
        foreach (var dir in Directory.EnumerateDirectories(from))
        {
            var name = Path.GetFileName(dir);
            if (name.StartsWith('.') || name is "node_modules" or "tests" or "tools") continue;
            CopyExtension(dir, Path.Combine(to, name), depth + 1);
        }
    }

    private static readonly HashSet<string> KeyLikeFiles = new(StringComparer.OrdinalIgnoreCase)
        { ".pem", ".key", ".crx", ".p12", ".pfx", ".der", ".jks", ".keystore" };
    private static readonly HashSet<string> ProfileFiles = new(StringComparer.OrdinalIgnoreCase) { ".streamDeckProfile" };
    private static readonly HashSet<string> LayoutFiles = new(StringComparer.OrdinalIgnoreCase) { ".json" };
    private static readonly HashSet<string> WebFiles = new(StringComparer.OrdinalIgnoreCase)
        { ".html", ".htm", ".js", ".css", ".svg", ".png", ".gif", ".jpg", ".jpeg", ".webp", ".woff2", ".json" };

    private static void CopyTree(string from, string to, Dictionary<string, string>? seen, List<string>? problems, HashSet<string> extensions)
    {
        if (!Directory.Exists(from)) return;
        foreach (var file in Directory.EnumerateFiles(from, "*", SearchOption.AllDirectories))
        {
            var rel = Path.GetRelativePath(from, file);
            if (!extensions.Contains(Path.GetExtension(file))) continue;
            var dest = Path.Combine(to, rel);
            if (seen is not null)
            {
                var key = Path.GetRelativePath(Path.GetDirectoryName(to)!, dest);
                if (seen.TryGetValue(key, out var first))
                {
                    problems?.Add($"{key} is provided twice ({first} and {file}); file names must be unique across projects");
                    continue;
                }
                seen[key] = file;
            }
            Directory.CreateDirectory(Path.GetDirectoryName(dest)!);
            File.Copy(file, dest, overwrite: true);
        }
    }
}
