using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace PrismControl.TokensGen;

/// <summary>
/// Turns Prism-ds/design/tokens.json into C# constants (Refraction.g.cs). Only values the Qt renderer can use are
/// emitted: hex colors, and rgba() split into a hex color + opacity. Gradients, shadows and CSS lengths are skipped
/// (listed in the generated header). Output is deterministic so the sync test can compare it byte for byte.
/// </summary>
public static partial class TokensGenerator
{
    public const string DefaultTokensPath = "../../Prism-ds/design/tokens.json";
    public const string OutputPath = "src/PrismControl.Core/Render/Tokens/Refraction.g.cs";

    private readonly record struct Rgba(byte R, byte G, byte B, double A);

    public static string Generate(string json)
    {
        var sha = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(json.Replace("\r\n", "\n")))).ToLowerInvariant();
        using var doc = JsonDocument.Parse(json);
        var root = doc.RootElement;
        var name = root.GetProperty("name").GetString() ?? "";
        var version = root.GetProperty("version").GetString() ?? "";

        var color = root.GetProperty("color");
        var rf = root.GetProperty("rf");
        var nightColor = color.GetProperty("night");
        var dayColor = color.GetProperty("day");

        // color.*: keys present in both themes, in document order.
        var colorKeys = nightColor.EnumerateObject().Select(p => p.Name).Where(k => dayColor.TryGetProperty(k, out _)).ToList();

        // rf.*: only keys whose night AND day values are plain colors.
        var rfNight = rf.GetProperty("night");
        var rfDay = rf.GetProperty("day");
        var rfKeys = new List<string>();
        var skipped = new List<string>();
        foreach (var p in rfNight.EnumerateObject())
        {
            if (!rfDay.TryGetProperty(p.Name, out var dv)) continue;
            if (colorKeys.Contains(p.Name)) { skipped.Add("rf." + p.Name + " (name clash)"); continue; }
            if (TryColor(p.Value.GetString(), out _) && TryColor(dv.GetString(), out _)) rfKeys.Add(p.Name);
            else skipped.Add("rf." + p.Name);
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("//   Generated by tools/PrismControl.TokensGen from Prism-ds/design/tokens.json. Do not edit by hand:");
        sb.AppendLine("//   dotnet run --project tools/PrismControl.TokensGen");
        sb.AppendLine($"//   Source: \"{name}\" v{version}, sha256 {sha}");
        sb.AppendLine("//   rgba() values are split into a hex color + opacity (the Stream Deck renderer draws rgba() black).");
        sb.AppendLine($"//   Skipped (not plain colors): {string.Join(", ", skipped)}");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using PrismControl.Core.Render;");
        sb.AppendLine();
        sb.AppendLine("namespace PrismControl.Core.Render.Tokens;");
        sb.AppendLine();

        // ---- RefractionPalette
        sb.AppendLine("/// <summary>One Refraction theme (Night or Day) as Qt-safe colors.</summary>");
        sb.AppendLine("public sealed partial class RefractionPalette");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>\"night\" or \"day\".</summary>");
        sb.AppendLine("    public required string Name { get; init; }");
        sb.AppendLine("    public required bool IsDark { get; init; }");
        foreach (var k in colorKeys)
        {
            var note = nightColor.GetProperty(k).TryGetProperty("note", out var n) ? n.GetString() : null;
            sb.AppendLine($"    /// <summary>color.{k}{(note is null ? "" : ": " + Xml(note))}</summary>");
            sb.AppendLine($"    public required Color {Pascal(k)} {{ get; init; }}");
        }
        foreach (var k in rfKeys)
        {
            sb.AppendLine($"    /// <summary>rf.{k}</summary>");
            sb.AppendLine($"    public required Paint {Pascal(k)} {{ get; init; }}");
        }
        sb.AppendLine("    /// <summary>deck.material fill: radial gradient stops (center top → edge) for the key body.</summary>");
        sb.AppendLine("    public required GradientStop[] KeyMaterial { get; init; }");
        sb.AppendLine("    /// <summary>deck.material edge: the lit top edge highlight.</summary>");
        sb.AppendLine("    public required Paint KeyEdge { get; init; }");
        sb.AppendLine("    public required Color KeyInk { get; init; }");
        sb.AppendLine("    public required Color KeyMuted { get; init; }");
        sb.AppendLine("    /// <summary>The 12-stop spectrum (violet → rose) for this theme.</summary>");
        sb.AppendLine("    public required IReadOnlyList<SpectrumColor> Spectrum { get; init; }");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("/// <summary>One spectrum stop for one theme. Wash is translucent (Night) or a pale solid (Day).</summary>");
        sb.AppendLine("public sealed record SpectrumColor(string Name, double Hue, string Lambda, Color Ink, Color Vivid, Paint Wash, Color? Sheen);");
        sb.AppendLine();

        // ---- Refraction static
        sb.AppendLine("/// <summary>Prism Refraction design tokens.</summary>");
        sb.AppendLine("public static partial class Refraction");
        sb.AppendLine("{");
        sb.AppendLine($"    public const string TokensName = \"{Esc(name)}\";");
        sb.AppendLine($"    public const string TokensVersion = \"{Esc(version)}\";");
        sb.AppendLine($"    public const string TokensSha256 = \"{sha}\";");
        sb.AppendLine();
        var spectrum = root.GetProperty("spectrum").GetProperty("stops").EnumerateArray().ToList();
        var material = root.GetProperty("deck").GetProperty("material");
        foreach (var theme in new[] { "night", "day" })
        {
            var c = theme == "night" ? nightColor : dayColor;
            var r = theme == "night" ? rfNight : rfDay;
            var m = material.GetProperty(theme);
            sb.AppendLine($"    public static RefractionPalette {Pascal(theme)} {{ get; }} = new()");
            sb.AppendLine("    {");
            sb.AppendLine($"        Name = \"{theme}\",");
            sb.AppendLine($"        IsDark = {(theme == "night" ? "true" : "false")},");
            foreach (var k in colorKeys)
                sb.AppendLine($"        {Pascal(k)} = {ColorExpr(c.GetProperty(k).GetProperty("hex").GetString()!)},");
            foreach (var k in rfKeys)
                sb.AppendLine($"        {Pascal(k)} = {PaintExpr(r.GetProperty(k).GetString()!)},");
            sb.AppendLine($"        KeyMaterial = [{string.Join(", ", GradientStops(m.GetProperty("fill").GetString()!))}],");
            sb.AppendLine($"        KeyEdge = {PaintExpr(LastColor(m.GetProperty("edge").GetString()!))},");
            sb.AppendLine($"        KeyInk = {ColorExpr(m.GetProperty("ink").GetString()!)},");
            sb.AppendLine($"        KeyMuted = {ColorExpr(m.GetProperty("muted").GetString()!)},");
            sb.AppendLine("        Spectrum =");
            sb.AppendLine("        [");
            foreach (var s in spectrum)
            {
                var t = s.GetProperty(theme);
                var ink = t.GetProperty("ink").GetProperty("hex").GetString()!;
                var vivid = t.GetProperty("vivid").GetProperty("hex").GetString()!;
                var washEl = t.GetProperty("wash");
                var wash = washEl.ValueKind == JsonValueKind.String ? washEl.GetString()! : washEl.GetProperty("hex").GetString()!;
                var sheen = t.TryGetProperty("sheen", out var sh) ? ColorExpr(sh.GetProperty("hex").GetString()!) : "null";
                sb.AppendLine($"            new(\"{Esc(s.GetProperty("name").GetString()!)}\", {Num(s.GetProperty("h").GetDouble())}, \"{Esc(s.GetProperty("lambda").GetString()!)}\", {ColorExpr(ink)}, {ColorExpr(vivid)}, {PaintExpr(wash)}, {sheen}),");
            }
            sb.AppendLine("        ],");
            sb.AppendLine("    };");
            sb.AppendLine();
        }

        // ---- Deck constants
        var deck = root.GetProperty("deck");
        var canvas = deck.GetProperty("canvas");
        var safe = deck.GetProperty("safe");
        var type = deck.GetProperty("type");
        sb.AppendLine("    /// <summary>deck.*: the Stream Deck key grammar (units are @144 for keys, 200×100 for dial segments).</summary>");
        sb.AppendLine("    public static class Deck");
        sb.AppendLine("    {");
        sb.AppendLine($"        public const double KeySize = {Num(canvas.GetProperty("key").GetProperty("2x").GetDouble())};");
        sb.AppendLine($"        public const double KeySize1x = {Num(canvas.GetProperty("key").GetProperty("1x").GetDouble())};");
        sb.AppendLine($"        public const double PlusKeyPixels = {Num(canvas.GetProperty("plusKey").GetDouble())};");
        sb.AppendLine($"        public const double XlKeyPixels = {Num(canvas.GetProperty("xlKey").GetDouble())};");
        sb.AppendLine($"        public const double DialWidth = {Num(canvas.GetProperty("dialSegment").GetProperty("w").GetDouble())};");
        sb.AppendLine($"        public const double DialHeight = {Num(canvas.GetProperty("dialSegment").GetProperty("h").GetDouble())};");
        sb.AppendLine($"        public const double GridUnit = {Num(deck.GetProperty("grid").GetProperty("unit").GetDouble())};");
        sb.AppendLine($"        public const double SafeBleed = {Num(safe.GetProperty("bleed").GetDouble())};");
        sb.AppendLine($"        public const double SafeContent = {Num(safe.GetProperty("content").GetDouble())};");
        sb.AppendLine($"        public const double SafeText = {Num(safe.GetProperty("text").GetDouble())};");
        foreach (var t in type.EnumerateObject())
        {
            if (t.Value.ValueKind != JsonValueKind.Object) continue;
            var p = Pascal(t.Name);
            if (t.Value.TryGetProperty("size", out var size)) sb.AppendLine($"        public const double {p}Size = {Num(size.GetDouble())};");
            if (t.Value.TryGetProperty("weight", out var w)) sb.AppendLine($"        public const int {p}Weight = {w.GetInt32()};");
            if (t.Value.TryGetProperty("tracking", out var tr) && tr.GetString() is { } trs && trs.EndsWith("em", StringComparison.Ordinal))
                sb.AppendLine($"        public const double {p}TrackingEm = {Num(double.Parse(trs[..^2], CultureInfo.InvariantCulture))};");
            if (t.Value.TryGetProperty("maxChars", out var mc)) sb.AppendLine($"        public const int {p}MaxChars = {mc.GetInt32()};");
            if (t.Value.TryGetProperty("maxCharsPerLine", out var mcl)) sb.AppendLine($"        public const int {p}MaxCharsPerLine = {mcl.GetInt32()};");
            if (t.Value.TryGetProperty("maxLines", out var ml)) sb.AppendLine($"        public const int {p}MaxLines = {ml.GetInt32()};");
            if (t.Value.TryGetProperty("transform", out var tf) && tf.GetString() == "uppercase") sb.AppendLine($"        public const bool {p}Uppercase = true;");
        }
        sb.AppendLine($"        public const string DefaultMaterial = \"{Esc(material.GetProperty("default").GetString()!)}\";");
        sb.AppendLine("    }");
        sb.AppendLine();

        sb.AppendLine("    /// <summary>radius.* in px.</summary>");
        sb.AppendLine("    public static class Radius");
        sb.AppendLine("    {");
        foreach (var p in root.GetProperty("radius").EnumerateObject())
            if (p.Value.ValueKind == JsonValueKind.Number) sb.AppendLine($"        public const double {Ident(p.Name)} = {Num(p.Value.GetDouble())};");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>motion.duration.* in ms.</summary>");
        sb.AppendLine("    public static class Motion");
        sb.AppendLine("    {");
        foreach (var p in root.GetProperty("motion").GetProperty("duration").EnumerateObject())
            if (p.Value.ValueKind == JsonValueKind.Number) sb.AppendLine($"        public const double {Ident(p.Name)}Ms = {Num(p.Value.GetDouble())};");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString().Replace("\r\n", "\n");
    }

    private static string Ident(string key)
    {
        var p = Pascal(key);
        return char.IsDigit(p[0]) ? "X" + p : p;
    }

    private static string Pascal(string key)
    {
        var sb = new StringBuilder();
        var up = true;
        foreach (var ch in key)
        {
            if (ch is '-' or '_' or '.' or ' ') { up = true; continue; }
            sb.Append(up ? char.ToUpperInvariant(ch) : ch);
            up = false;
        }
        return sb.ToString();
    }

    private static IEnumerable<string> GradientStops(string css)
    {
        foreach (Match m in StopRe().Matches(css))
        {
            var c = ParseHex(m.Groups[1].Value);
            var offset = double.Parse(m.Groups[2].Value, CultureInfo.InvariantCulture) / 100;
            yield return $"new GradientStop({Num(offset)}, new Color(0x{c.R:x2}, 0x{c.G:x2}, 0x{c.B:x2}))";
        }
    }

    private static string LastColor(string css)
    {
        var all = ColorTokenRe().Matches(css);
        if (all.Count == 0) throw new FormatException("no color in " + css);
        return all[^1].Value;
    }

    private static bool TryColor(string? s, out Rgba c)
    {
        c = default;
        if (s is null) return false;
        s = s.Trim();
        if (s == "transparent") { c = new Rgba(0, 0, 0, 0); return true; }
        if (s.StartsWith('#') && (s.Length == 7 || s.Length == 4))
        {
            c = ParseHex(s);
            return true;
        }
        var m = RgbaRe().Match(s);
        if (m.Success)
        {
            c = new Rgba(byte.Parse(m.Groups[1].Value, CultureInfo.InvariantCulture), byte.Parse(m.Groups[2].Value, CultureInfo.InvariantCulture),
                byte.Parse(m.Groups[3].Value, CultureInfo.InvariantCulture), m.Groups[4].Success ? double.Parse(m.Groups[4].Value, CultureInfo.InvariantCulture) : 1);
            return true;
        }
        return false;
    }

    private static Rgba ParseHex(string hex)
    {
        var h = hex.TrimStart('#');
        if (h.Length == 3) h = string.Concat(h.Select(ch => new string(ch, 2)));
        return new Rgba(Convert.ToByte(h[..2], 16), Convert.ToByte(h[2..4], 16), Convert.ToByte(h[4..6], 16), 1);
    }

    private static string ColorExpr(string hex)
    {
        var c = ParseHex(hex);
        return $"new Color(0x{c.R:x2}, 0x{c.G:x2}, 0x{c.B:x2})";
    }

    private static string PaintExpr(string css)
    {
        if (!TryColor(css, out var c)) throw new FormatException("not a color: " + css);
        if (css.Trim() == "transparent") return "Paint.None";
        var col = $"new Color(0x{c.R:x2}, 0x{c.G:x2}, 0x{c.B:x2})";
        return c.A >= 1 ? $"Paint.Solid({col})" : $"Paint.Solid({col}, {Num(c.A)})";
    }

    private static string Num(double v) => v.ToString("0.####", CultureInfo.InvariantCulture);
    private static string Esc(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");
    private static string Xml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    [GeneratedRegex(@"#([0-9a-fA-F]{6})\s+([0-9.]+)%")] private static partial Regex StopRe();
    [GeneratedRegex(@"#[0-9a-fA-F]{6}\b|rgba?\([^)]*\)")] private static partial Regex ColorTokenRe();
    [GeneratedRegex(@"^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([0-9.]+)\s*)?\)$")] private static partial Regex RgbaRe();
}
